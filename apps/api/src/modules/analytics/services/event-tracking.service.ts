import { Injectable, Logger, BadRequestException } from '@nestjs/common';
import { InjectDataSource } from '@nestjs/typeorm';
import { DataSource } from 'typeorm';
import {
  TrackEventDto,
  AllowedAnalyticsEvent,
  CLIENT_PERMITTED_EVENTS,
} from '../dto/track-event.dto';
import { sanitizeAnalyticsProperties } from '../utils/event-sanitizer.util';
import type { AuthenticatedUser } from '../../../common/decorators/current-user.decorator';

@Injectable()
export class EventTrackingService {
  private readonly logger = new Logger(EventTrackingService.name);

  constructor(
    @InjectDataSource()
    private readonly dataSource: DataSource,
  ) {}

  /**
   * Tracks an event emitted from client browsers.
   * Enforces that clients can only emit user-interaction events (searches, profile views, booking start).
   * Clients CANNOT claim server-authoritative events (such as booking_confirmed or session_completed).
   */
  async trackClientEvent(
    dto: TrackEventDto,
    actor?: AuthenticatedUser,
  ): Promise<{ recorded: boolean }> {
    if (!CLIENT_PERMITTED_EVENTS.has(dto.eventName)) {
      throw new BadRequestException(
        `Clients are not permitted to emit server-authoritative event: '${dto.eventName}'.`,
      );
    }

    const sanitizedProps = sanitizeAnalyticsProperties(dto.properties);
    const actorUserId = actor?.id ?? null;
    const actorRole = actor?.roles?.[0] ?? 'anonymous';
    const environment = process.env.NODE_ENV || 'development';
    const clientTimestamp = dto.clientTimestamp ? new Date(dto.clientTimestamp) : null;

    try {
      await this.dataSource.query(
        `INSERT INTO product_analytics_events (
           event_name, actor_user_id, actor_role, session_id, entity_type, entity_id, properties, environment, client_timestamp
         ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9);`,
        [
          dto.eventName,
          actorUserId,
          actorRole,
          dto.sessionId || null,
          dto.entityType || null,
          dto.entityId || null,
          JSON.stringify(sanitizedProps),
          environment,
          clientTimestamp,
        ],
      );
      return { recorded: true };
    } catch (err) {
      this.logger.warn(
        `Failed to record client analytics event '${dto.eventName}': ${(err as Error).message}`,
      );
      return { recorded: false };
    }
  }

  /**
   * Tracks a trusted, server-side lifecycle event generated by platform business logic.
   * Completely isolated: failures never interrupt critical business workflows.
   */
  async trackServerEvent(
    eventName: AllowedAnalyticsEvent,
    options: {
      actorUserId?: string | null;
      actorRole?: string;
      sessionId?: string | null;
      entityType?: string | null;
      entityId?: string | null;
      properties?: Record<string, unknown>;
    } = {},
  ): Promise<boolean> {
    const sanitizedProps = sanitizeAnalyticsProperties(options.properties);
    const environment = process.env.NODE_ENV || 'development';

    try {
      await this.dataSource.query(
        `INSERT INTO product_analytics_events (
           event_name, actor_user_id, actor_role, session_id, entity_type, entity_id, properties, environment
         ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8);`,
        [
          eventName,
          options.actorUserId || null,
          options.actorRole || 'system',
          options.sessionId || null,
          options.entityType || null,
          options.entityId || null,
          JSON.stringify(sanitizedProps),
          environment,
        ],
      );
      return true;
    } catch (err) {
      this.logger.warn(
        `Failed to record server analytics event '${eventName}': ${(err as Error).message}`,
      );
      return false;
    }
  }
}
